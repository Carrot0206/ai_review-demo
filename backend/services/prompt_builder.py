TERMINATION_PROMPT_PROFILE_DEFAULT = "general_explanation"


def _prompt_profile_for_rules(process: str, rules: list[Rule]) -> str:
    if process not in {"initial", "pre_registration", "pre_report", "termination"} or not rules:
        return ""
    if process == "pre_registration":
        default_profile = PRE_REGISTRATION_PROMPT_PROFILE_DEFAULT
    elif process == "pre_report":
        default_profile = PRE_REPORT_PROMPT_PROFILE_DEFAULT
    elif process == "termination":
        default_profile = TERMINATION_PROMPT_PROFILE_DEFAULT
    else:
        default_profile = INITIAL_PROMPT_PROFILE_DEFAULT
    profiles = {r.rule_type or default_profile for r in rules}
    if len(profiles) == 1:
        return next(iter(profiles))
    return default_profile


def _system_prompt_for_rules(process: str, rules: list[Rule]) -> tuple[str, str]:
    system_prompt = PROCESS_SYSTEM_PROMPTS.get(process)
    if system_prompt is None:
        raise ValueError(f"未配置流程 system prompt: {process}")
    profile = _prompt_profile_for_rules(process, rules)
    if process == "initial" and profile:
        system_prompt = f"{system_prompt}\n\n{INITIAL_RULE_TYPE_PROMPTS.get(profile, INITIAL_RULE_TYPE_PROMPTS[INITIAL_PROMPT_PROFILE_DEFAULT])}"
    elif process == "pre_registration" and profile:
        system_prompt = f"{system_prompt}\n\n{PRE_REGISTRATION_RULE_TYPE_PROMPTS.get(profile, PRE_REGISTRATION_RULE_TYPE_PROMPTS[PRE_REGISTRATION_PROMPT_PROFILE_DEFAULT])}"
    elif process == "pre_report" and profile:
        system_prompt = f"{system_prompt}\n\n{PRE_REPORT_RULE_TYPE_PROMPTS.get(profile, PRE_REPORT_RULE_TYPE_PROMPTS[PRE_REPORT_PROMPT_PROFILE_DEFAULT])}"
    elif process == "termination" and profile:
        system_prompt = f"{system_prompt}\n\n{TERMINATION_RULE_TYPE_PROMPTS.get(profile, TERMINATION_RULE_TYPE_PROMPTS[TERMINATION_PROMPT_PROFILE_DEFAULT])}"
    return system_prompt, profile


def _rule_to_prompt_obj(rule: Rule) -> dict[str, Any]:
    """精简规则字段送进 prompt，避免 token 浪费。"""
    return {
        "rule_id": rule.rule_id,
        "rule_name": rule.rule_name,
        "rule_text": rule.rule_text,
        "review_dimension": rule.review_dimension,
        "rule_type": rule.rule_type,
        "applicable_materials": rule.applicable_materials,
        "operator": rule.operator,
        "script_params": rule.script_params,
        "check_type": rule.check_type,
        "table_name": rule.table_name,
        "field_name": rule.field_name,
        "trigger_condition": rule.trigger_condition,
        "machine_params": rule.machine_params,
        "rule_role": rule.rule_role,
        "severity_type": rule.severity_type,
        "issue_type": rule.issue_type,
        "field_anchor": rule.field_anchor,
        "skip_when": rule.skip_when,
        "ai_check_focus": rule.ai_check_focus,
        "evidence_requirement": rule.evidence_requirement,
    }


def _material_to_text(material: ExtractedMaterial, max_chars_per_segment: int = 1500) -> str:
    """把一份材料渲染成纯文本块。"""
    lines = [f"### 材料：{material.material_name}（类型：{material.material_type}，格式：{material.file_kind}）"]
    for seg in material.segments:
        text = seg.text
        if len(text) > max_chars_per_segment:
            text = text[:max_chars_per_segment] + "……[已截断]"
        lines.append(f"[{seg.location}] {text}")
    return "\n".join(lines)


def build_messages(
    process: str,
    rules: list[Rule],
    materials: list[ExtractedMaterial],
    material_filter: Optional[set[str]] = None,
) -> list[dict[str, str]]:
    """构造 chat.completions 的 messages。

    material_filter：限定本次只送入哪些 material_type 的材料；为 None 表示全发。
    若过滤后为空，仍保留 1 行占位提示，使模型可以走"未发现问题"分支。
    """
    system_prompt, prompt_profile = _system_prompt_for_rules(process, rules)

    process_label = PROCESS_LABEL.get(process, process)
    rule_list = [_rule_to_prompt_obj(r) for r in rules]

    if material_filter is None:
        filtered = list(materials)
    else:
        filtered = [m for m in materials if m.material_type in material_filter]

    if filtered:
        materials_text = "\n\n".join(_material_to_text(m) for m in filtered)
    else:
        materials_text = "### 无可审材料（本批次依赖的材料类型在本次上传中未提供）"

    user_content = f"""## 登记流程
{process_label}

## 本次需要审查的规则（共 {len(rules)} 条，请逐条独立判断）
Prompt Profile：{prompt_profile or "default"}
```json
{json.dumps(rule_list, ensure_ascii=False, indent=2)}
```

## 申请材料

{materials_text}
"""
    return [
        {"role": "system", "content": system_prompt},
        {"role": "user", "content": user_content},
    ]
